import assert from 'node:assert/strict';
import { homeMetrics, homePage, homeSubjectRows, studyDay } from '../home-ui.js';
const now = new Date('2026-11-03T00:10:00Z');
assert.equal(studyDay('2026-11-02T23:30:00Z'), studyDay(now));
assert.equal(studyDay('invalid'), '');
const empty = homeMetrics({ now });
assert.equal(empty[0].value, '—');
assert.equal(empty[1].value, '—');
const metrics = homeMetrics({ now, profile: { rhythm: 1, tests: { tests_taken: 3, tests_today: 1, average_score: 75 } }, attempts: [{ timestamp: '2026-11-02T23:30:00Z' }, { timestamp: '2026-11-02T22:30:00Z' }] });
assert.deepEqual(metrics.map(x => x.value), ['3', '75%', '1', '1 day']);
const subjects = Array.from({ length: 10 }, (_, i) => ({ id: String(i), name: `Subject ${i}`, description: 'Preparation', stats: { count: 0 } }));
assert.match(homeSubjectRows(subjects), />10<\/span>/);
assert.match(homeSubjectRows(subjects, 'absent'), /No subjects match/);
assert.equal((homeSubjectRows(subjects, 'Subject 2').match(/data-home-subject=/g) || []).length, 1);
const options = { now, name: '<script>alert(1)</script>', greeting: 'Good morning', subjects };
const aspirant = homePage({ ...options, sprintDone: true });
assert.ok(!aspirant.includes('<script>'));
assert.match(aspirant, /id="start-sprint"[^>]*disabled/);
assert.match(aspirant, /id="home-saved"/);
assert.ok(!aspirant.includes('vs yesterday'));
const university = homePage({ ...options, university: true });
assert.match(university, /id="uni-home-open-courses"/);
assert.match(university, /data-uni-browse-dept="anatomy"/);
assert.ok(!university.includes('id="start-sprint"'));
console.log('Home UI checks passed.');
